import {createRequire} from 'node:module';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
const native=createRequire(new URL('../packages/dem-parser/package.json',import.meta.url))('@cs2-analyst/demoparser-native');
const history=JSON.parse(readFileSync('./docs/deep-review-personal-native-probe.json','utf8'));
const bytes=readFileSync('./.demo/demo2.dem');
const fields=['X','Y','Z','yaw','pitch','health','is_alive','team_num','active_weapon_name'];
const rows=native.parseTicks(bytes,fields,history.ticks,[history.affectedPlayerId]);
const result={fixture:history.fixture,sha256:history.sha256,nativeBinding:native.getBindingProvenance(),historicalProbe:'docs/deep-review-personal-native-probe.json',affectedPlayerId:history.affectedPlayerId,ticks:history.ticks,fields,rows,coreFieldsAvailable:rows.every(r=>fields.filter(f=>f!=='active_weapon_name').every(f=>r[f]!==null&&r[f]!==undefined))};
mkdirSync('vendor/demoparser/.build',{recursive:true});
writeFileSync('vendor/demoparser/.build/fixed-production-native-probe.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
